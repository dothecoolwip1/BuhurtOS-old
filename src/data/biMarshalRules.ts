export type BiRuleSource = {
  id: string;
  title: string;
  version: string;
  scope: string;
  url: string;
  publishedLabel: string;
};

export type BiRuleEntry = {
  id: string;
  sourceId: string;
  section: string;
  title: string;
  appliesTo: RuleFormat[];
  tags: string[];
  summary: string;
  details?: string[];
  marshalCall?: string;
  penalty?: string;
};

const source = (id: string, title: string, version: string, scope: string, url: string, publishedLabel: string): BiRuleSource => ({
  id, title, version, scope, url, publishedLabel
});

const rule = (
  sourceId: string,
  section: string,
  title: string,
  appliesTo: RuleFormat[],
  tags: string[],
  summary: string,
  details?: string[],
  marshalCall?: string,
  penalty?: string
): BiRuleEntry => ({
  id: `${sourceId}-${section.toLowerCase().replace(/[^a-z0-9]+/g, '-')}`,
  sourceId, section, title, appliesTo, tags, summary, details, marshalCall, penalty
});

